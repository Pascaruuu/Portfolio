import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const viewportSrcPath = resolve(root, 'src/lib/viewport.svelte.ts');
const outPath = resolve(root, 'generated/breakpoints.css');

/**
 * @param {string} source
 * @param {string} name
 */
function extractConst(source, name) {
	const match = source.match(new RegExp(`export const ${name}\\s*=\\s*(\\d+)`));
	if (!match) throw new Error(`generate-breakpoints: could not find "${name}" in ${viewportSrcPath}`);
	return match[1];
}

export function generateBreakpointsCss() {
	const source = readFileSync(viewportSrcPath, 'utf-8');
	const bpDesktop = extractConst(source, 'BP_DESKTOP');
	const bpWelcomeStack = extractConst(source, 'BP_WELCOME_STACK');
	const welcomeCompactH = extractConst(source, 'WELCOME_COMPACT_H');

	const css = `/* AUTO-GENERATED by scripts/generate-breakpoints.mjs from viewport.svelte.ts — do not edit by hand. */
@custom-media --mobile (max-width: ${bpDesktop}px);
@custom-media --welcome-stack (max-width: ${bpWelcomeStack}px);
@custom-media --welcome-compact-height (max-height: ${welcomeCompactH}px);
`;

	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(outPath, css);
	return outPath;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	generateBreakpointsCss();
}
